package com.abyssia.client.light;

import com.abyssia.Abyssia;
import com.abyssia.item.light.HandLampItem;
import net.minecraft.client.renderer.item.ItemProperties;
import net.minecraft.core.registries.BuiltInRegistries;
import net.minecraft.resources.ResourceLocation;
import net.minecraft.world.item.Item;
import net.neoforged.api.distmarker.Dist;
import net.neoforged.bus.api.SubscribeEvent;
import net.neoforged.fml.common.EventBusSubscriber;
import net.neoforged.fml.event.lifecycle.FMLClientSetupEvent;

/**
 * Item model predicate abyssia:on (1 while the hand lamp's "On" data is set) so models/item/hand_lamp.json can switch
 * to hand_lamp_on.json (glowing lens). Models are generated by tools/hand_lamp_assets.py.
 */
@EventBusSubscriber(modid = Abyssia.MODID, value = Dist.CLIENT)
public final class HandLampItemProperty
{
    private HandLampItemProperty() {}

    @SubscribeEvent
    public static void onClientSetup(FMLClientSetupEvent event)
    {
        event.enqueueWork(() ->
        {
            Item lamp = BuiltInRegistries.ITEM.get(ResourceLocation.fromNamespaceAndPath(Abyssia.MODID, "hand_lamp"));
            if (lamp instanceof HandLampItem)
                ItemProperties.register(lamp, ResourceLocation.fromNamespaceAndPath(Abyssia.MODID, "on"),
                        (stack, level, entity, seed) -> HandLampItem.isOn(stack) ? 1f : 0f);
        });
    }
}
