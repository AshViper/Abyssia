package com.abyssia.client.light;

import com.abyssia.Abyssia;
import com.abyssia.item.light.HandLampItem;
import net.minecraft.client.renderer.item.ItemProperties;
import net.minecraft.resources.ResourceLocation;
import net.minecraft.world.item.Item;
import net.minecraftforge.api.distmarker.Dist;
import net.minecraftforge.eventbus.api.SubscribeEvent;
import net.minecraftforge.fml.common.Mod;
import net.minecraftforge.fml.event.lifecycle.FMLClientSetupEvent;
import net.minecraftforge.registries.ForgeRegistries;

/**
 * Item model predicate abyssia:on (1 while the hand lamp's "On" tag is set) so models/item/hand_lamp.json can switch
 * to hand_lamp_on.json (glowing lens). Models are generated by tools/hand_lamp_assets.py.
 */
@Mod.EventBusSubscriber(modid = Abyssia.MODID, bus = Mod.EventBusSubscriber.Bus.MOD, value = Dist.CLIENT)
public final class HandLampItemProperty
{
    private HandLampItemProperty() {}

    @SubscribeEvent
    public static void onClientSetup(FMLClientSetupEvent event)
    {
        event.enqueueWork(() ->
        {
            Item lamp = ForgeRegistries.ITEMS.getValue(new ResourceLocation(Abyssia.MODID, "hand_lamp"));
            if (lamp instanceof HandLampItem)
                ItemProperties.register(lamp, new ResourceLocation(Abyssia.MODID, "on"),
                        (stack, level, entity, seed) -> HandLampItem.isOn(stack) ? 1f : 0f);
        });
    }
}
