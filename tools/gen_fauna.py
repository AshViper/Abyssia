DATA = os.path.join(MAIN, "resources", "data")
JAVA_DIR = os.path.join(MAIN, "java", "com", "abyssia", "client", "entity", "model")
GENERATOR_OUTPUT = os.path.join(HERE, "bbmodel-generator", "output")


def write_json(path, obj):
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w", encoding="utf-8") as f:
        json.dump(obj, f, indent=2, ensure_ascii=False)
        f.write("\n")


def species():
    return fauna.species()


def sid(s):
    return s.__name__.rsplit(".", 1)[-1]


# ================================================================ items (also called by gen_deep_assets.py)

ITEM_NAMES = {}
for _s in species():
    _en, _ja = _s.INFO["names"]
    ITEM_NAMES[sid(_s) + "_spawn_egg"] = (_en + " Spawn Egg", _ja + "のスポーンエッグ")
# "<item>.dropped_by": which species drop an item (from INFO["loot"]), shown as a JEI info page (com.abyssia.compat.jei)
_DROPPERS = {}
for _s in species():
    for _d in _s.INFO.get("loot", []):
        if ":" not in _d["item"]:
            _DROPPERS.setdefault(_d["item"], []).append(_s.INFO["names"])
for _item, _names in _DROPPERS.items():
    ITEM_NAMES[_item + ".dropped_by"] = ("Dropped by: " + ", ".join(n[0] for n in _names),
                                         "落とす生物: " + "、".join(n[1] for n in _names))


def item_models(write, im):
    for s in species():
        write(im(sid(s) + "_spawn_egg"), {"parent": "minecraft:item/template_spawn_egg"})


# ================================================================ models from the generator

def generator_outputs():
    """{creature id: its output folder} from the generator's manifests."""
    found = {}
    for manifest in glob.glob(os.path.join(GENERATOR_OUTPUT, "*", "*.json")):
        with open(manifest, encoding="utf-8") as f:
            found[json.load(f)["id"]] = os.path.dirname(manifest)
    return found


def sync_models():
    outputs = generator_outputs()
    tex = os.path.join(ASSETS, "textures", "entity")
    os.makedirs(tex, exist_ok=True)
    os.makedirs(JAVA_DIR, exist_ok=True)
    for s in species():
        name = sid(s)
        folder = outputs.get(name)
        if folder is None:
            raise SystemExit(f"no generated model for {name} in {GENERATOR_OUTPUT} (run node tools/bbmodel-generator/cli.js {name})")
        for java in glob.glob(os.path.join(folder, "*Geometry.java")) + glob.glob(os.path.join(folder, "*Animations.java")):
            shutil.copyfile(java, os.path.join(JAVA_DIR, os.path.basename(java)))
        shutil.copyfile(os.path.join(folder, name + ".png"), os.path.join(tex, name + ".png"))
        glow = os.path.join(folder, name + "_glow.png")
        if os.path.exists(glow):
            shutil.copyfile(glow, os.path.join(tex, name + "_glow.png"))
        elif os.path.exists(os.path.join(tex, name + "_glow.png")):
            os.remove(os.path.join(tex, name + "_glow.png"))
    print(f"  models of {len(species())} species synced from the generator")


def halo_texture():
    """The soft light around a light organ (drawn additively, tinted per animal): white core, smooth falloff."""
    import numpy as np
    from PIL import Image
    n = 32
    y, x = np.mgrid[0:n, 0:n] + 0.5
    r = np.hypot(x - n / 2, y - n / 2) / (n / 2)
    i = np.clip(np.exp(-r * r * 4.5) - np.exp(-4.5), 0, None) / (1 - np.exp(-4.5))
    v = (np.clip(i ** 1.2, 0, 1) * 255).astype(np.uint8)
    Image.fromarray(np.dstack([v, v, v, np.full_like(v, 255)]), "RGBA").save(os.path.join(ASSETS, "textures", "entity", "glow_halo.png"))


# ================================================================ sounds

def sounds(synthesise=True):
    import fauna_sounds
    table = {}
    for s in species():
        name = sid(s)
        folder = os.path.join(ASSETS, "sounds", "entity", name)
        if synthesise:
            shutil.rmtree(folder, ignore_errors=True)
        for kind, (variants, sub_en, _) in s.INFO["sounds"].items():
            if synthesise:
                try:
                    files = fauna_sounds.generate(s.INFO.get("voice", name), kind, variants, folder, name)
                except KeyError:
                    raise SystemExit(f"{name}: voice {s.INFO.get('voice', name)!r} has no {kind!r} sound in fauna_sounds.py "
                                     f"(add it there or pick a voice that has it)")
            else:
                files = [f"abyssia:entity/{name}/{kind}{n}" for n in range(1, variants + 1)]
            entry = {"sounds": files}
            if sub_en:
                entry["subtitle"] = f"subtitles.abyssia.entity.{name}.{kind}"
            elif kind == "step":
                entry["subtitle"] = "subtitles.block.generic.footsteps"
            table[f"entity.{name}.{kind}"] = entry
    write_json(os.path.join(ASSETS, "sounds.json"), table)
    print(f"  {len(table)} sound events")


