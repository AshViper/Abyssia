"""Builds Abyssia's deep-sea fauna assets around the models from tools/bbmodel-generator.

The models themselves (geometry, keyframe animations, textures, glow masks) are generated by tools/bbmodel-generator
(`node tools/bbmodel-generator/cli.js all`); this script copies them into the mod and adds everything else from the
species modules in tools/fauna/ (research notes + INFO: names, spawn egg colours, sounds, spawn rule):

* models: output/<Name>/<Id>Geometry.java, <Id>Animations.java -> client/entity/model/; <id>.png, <id>_glow.png ->
  textures/entity/ (never hand-edit these: change the creature definition in the generator and regenerate)
* sounds (sounds/entity/<id>/*.ogg, synthesised by fauna_sounds.py) and sounds.json
* spawn rules (data/abyssia/fauna_spawns/<id>.json, read by com.abyssia.fauna.FaunaSpawnRules), entity loot tables,
  the fauna tags, the light-organ halo sprite
* translations (entity names, spawn eggs, subtitles)
* for species with INFO["java"]: registry/GeneratedFauna.java + client/entity/GeneratedFaunaRenderers.java (fauna_java.py)

    python tools/gen_fauna.py                    # everything
    python tools/gen_fauna.py --no-sounds        # skip the (slow) sound synthesis

gen_deep_assets.py wipes models/item and rewrites the block/item translations, so it calls item_models() and takes
ITEM_NAMES from here: spawn eggs survive a full asset regeneration.
"""
