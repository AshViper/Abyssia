def data():
    a = lambda names: ["abyssia:" + n for n in names]
    tags = os.path.join(DATA, "abyssia", "tags")
    # habitat block tags the spawn rules test against (vanilla stone and sediments count in the ocean world)
    write_json(os.path.join(tags, "blocks", "fauna", "rock.json"), {"values": a(ROCK) + ["#minecraft:base_stone_overworld"]})
    write_json(os.path.join(tags, "blocks", "fauna", "soft_sediment.json"), {"values": a(SOFT) + [
        "#minecraft:sand", "minecraft:gravel", "minecraft:clay", "minecraft:mud"]})
    write_json(os.path.join(tags, "blocks", "fauna", "vegetation.json"), {"values": a(VEGETATION) + [
        "minecraft:seagrass", "minecraft:tall_seagrass", "minecraft:kelp", "minecraft:kelp_plant"]})
    write_json(os.path.join(tags, "blocks", "fauna", "crystal.json"), {"values": a(CRYSTAL)})
    write_json(os.path.join(tags, "blocks", "fauna", "vent.json"), {"values": a(VENT)})
    # who eats what: each species module lists its prey in INFO["prey"]; small fish are vanilla's
    ids = {sid(s) for s in species()}
    for s in species():
        prey = s.INFO.get("prey")
        if prey is not None:
            values = [p if ":" in p else "abyssia:" + p for p in prey if ":" in p or p in ids]
            write_json(os.path.join(tags, "entity_types", sid(s) + "_prey.json"), {"values": values})
    small_fish = ["minecraft:cod", "minecraft:salmon", "minecraft:tropical_fish"]
    write_json(os.path.join(tags, "entity_types", "lured_by_light.json"), {"values": small_fish + [
        "abyssia:" + p for p in ("deep_sea_shrimp", "ohara_shrimp") if p in ids]})
    # what small midwater and vent animals flee from
    threats = ("anglerfish", "gulper_eel", "viperfish", "goblin_shark", "frilled_shark", "giant_squid", "yunohana_crab", "vent_eelpout")
    write_json(os.path.join(tags, "entity_types", "small_fauna_threats.json"), {"values": ["abyssia:" + t for t in threats if t in ids]})
    # larger predators that turn toward a jelly's "burglar alarm" display (Atolla)
    responders = ("goblin_shark", "frilled_shark", "giant_squid")
    write_json(os.path.join(tags, "entity_types", "alarm_responders.json"), {"values": ["abyssia:" + t for t in responders if t in ids]})
    write_json(os.path.join(tags, "items", "isopod_food.json"), {"values": [
        "#minecraft:fishes", "minecraft:rotten_flesh", "minecraft:beef", "minecraft:porkchop", "minecraft:chicken",
        "minecraft:mutton", "minecraft:rabbit"]})

    rules = os.path.join(DATA, "abyssia", "fauna_spawns")
    shutil.rmtree(rules, ignore_errors=True)
    for s in species():
        name = sid(s)
        sp = s.INFO["spawn"]
        lo, core_lo, core_hi, hi = sp["depth_m"]
        rule = {"entity": "abyssia:" + name, "role": s.INFO["role"], "weight": sp["weight"],
                "group": {"min": sp["group"][0], "max": sp["group"][1]},
                "depth_m": {"min": lo, "core_min": core_lo, "core_max": core_hi, "max": hi},
                "placement": sp["placement"], "cave_factor": sp["cave_factor"], "open_factor": sp["open_factor"],
                "max_light": sp["max_light"], "cap": {"count": sp["cap"][0], "radius": sp["cap"][1]}}
        for key in ("habitat", "substrate", "biomes", "clearance"):
            if sp.get(key):
                rule[key] = sp[key]
        write_json(os.path.join(rules, name + ".json"), rule)
        write_json(os.path.join(DATA, "abyssia", "loot_tables", "entities", name + ".json"), loot_table(name, s.INFO.get("loot", [])))
    print(f"  spawn rules, loot tables and tags for {len(species())} species")


def loot_table(name, drops):
    """Entity loot: none for the fauna (user choice) unless a species lists INFO["loot"].
    A drop is dict(item, count=(min, max), looting=extra per level, chance=p); bare ids are abyssia items."""
    pools = []
    for d in drops:
        item = d["item"] if ":" in d["item"] else "abyssia:" + d["item"]
        lo, hi = d.get("count", (1, 1))
        functions = [{"function": "minecraft:set_count", "count": {"type": "minecraft:uniform", "min": lo, "max": hi}}]
        if d.get("looting"):
            functions.append({"function": "minecraft:looting_enchant", "count": {"type": "minecraft:uniform", "min": 0, "max": d["looting"]}})
        pool = {"rolls": 1, "entries": [{"type": "minecraft:item", "name": item, "functions": functions}]}
        if d.get("chance"):
            pool["conditions"] = [{"condition": "minecraft:random_chance_with_looting", "chance": d["chance"], "looting_multiplier": 0.05}]
        pools.append(pool)
    return {"type": "minecraft:entity", "pools": pools, "random_sequence": "abyssia:entities/" + name}


# ================================================================ translations

def lang():
    for code, idx in (("en_us", 0), ("ja_jp", 1)):
        path = os.path.join(ASSETS, "lang", code + ".json")
        old = json.load(open(path, encoding="utf-8")) if os.path.exists(path) else {}
        keep = {k: v for k, v in old.items() if not k.startswith(("entity.abyssia.", "subtitles.abyssia.entity."))
                and not (k.startswith("item.abyssia.") and k.endswith(".dropped_by"))}
        for s in species():
            name = sid(s)
            keep["entity.abyssia." + name] = s.INFO["names"][idx]
            for kind, (_, sub_en, sub_ja) in s.INFO["sounds"].items():
                if sub_en:
                    keep[f"subtitles.abyssia.entity.{name}.{kind}"] = (sub_en, sub_ja)[idx]
        for item, names in ITEM_NAMES.items():
            keep["item.abyssia." + item] = names[idx]
        write_json(path, dict(sorted(keep.items())))


def main():
    args = sys.argv[1:]
    sync_models()
    # Java registration of the data-driven species (INFO["java"]); the original 21 are hand-written
    import fauna_java
    fauna_java.generate(species(), sid, generator_outputs())
    halo_texture()
    sounds(synthesise="--no-sounds" not in args)
    data()
    lang()
    # spawn egg item models live in models/item, which gen_deep_assets.py owns and regenerates
    im = lambda n: os.path.join(ASSETS, "models", "item", n + ".json")
    item_models(write_json, im)
    print("fauna done")


if __name__ == "__main__":
    main()
